// Writes the sprite sources of a design module (tools/creature-designs/*.js) into
// src/gfx/sources/creatures/<id>.js. Usage: npm run creature-design -- <design file> [...]
// A design module exports `line`: [{ id, front, back, icon }], 48 × 48 views and a 16 × 16 icon.
// Re-exporting overwrites the sprite file: retouch pixels in the design, or stop exporting it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { CREATURES_BY_ID } from '../src/data/creatures.js';
import { validateSprite } from '../src/gfx/sprite-utils.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = path.join(ROOT, 'src', 'gfx', 'sources', 'creatures');

const block = (name, rows) => `  ${name}: [\n${rows.map((row) => `    '${row}',`).join('\n')}\n  ],\n`;

export function spriteSource(entry, designFile) {
  const species = CREATURES_BY_ID[entry.id];
  if (!species) throw new Error(`Unknown species: ${entry.id}`);
  for (const [view, size] of [['front', 48], ['back', 48], ['icon', 16]]) {
    const errors = validateSprite(entry[view], { width: size, height: size });
    if (errors.length > 0) throw new Error(`${entry.id}/${view}: ${errors.join('; ')}`);
  }
  return `// ${species.name} (bestiaire V2), generated by npm run creature-design from ${designFile}.\n`
    + "// Sprite (48 × 48) and party icon (16 × 16): '0'-'3' = palette index, '.' = transparent.\n"
    + 'export default {\n' + block('front', entry.front) + block('back', entry.back) + block('icon', entry.icon) + '};\n';
}

async function main(files) {
  if (files.length === 0) throw new Error('Usage: npm run creature-design -- <design file> [...]');
  for (const file of files) {
    const designFile = path.relative(ROOT, path.resolve(file)).replace(/\\/g, '/');
    const { line } = await import(pathToFileURL(path.resolve(file)).href);
    for (const entry of line) {
      fs.writeFileSync(path.join(SOURCES, `${entry.id}.js`), spriteSource(entry, designFile));
      process.stdout.write(`${entry.id} ← ${designFile}\n`);
    }
  }
  process.stdout.write('Ajouter les nouvelles espèces à src/gfx/sources/creatures/index.js, puis npm run atlas.\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exit(1);
  });
}
