// npm run build-web: builds the web version in _site/ (published by .github/workflows/pages.yml).
// Copies src/ (without the debug tools), assets/ and the icon, adds the root redirect, and writes
// the list of files the service worker keeps for offline play (src/precache-manifest.js).
// Uses only Node built-ins, so the workflow needs no npm install.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = path.join(ROOT, '_site');

function listFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    return entry.isDirectory() ? listFiles(full) : [full];
  });
}

function build() {
  fs.rmSync(SITE, { recursive: true, force: true });
  fs.cpSync(path.join(ROOT, 'src'), path.join(SITE, 'src'), { recursive: true });
  fs.rmSync(path.join(SITE, 'src', 'debug'), { recursive: true, force: true });
  fs.cpSync(path.join(ROOT, 'assets'), path.join(SITE, 'assets'), { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'build', 'icon.png'), path.join(SITE, 'src', 'icon.png'));
  fs.copyFileSync(path.join(ROOT, 'tools', 'pages-index.html'), path.join(SITE, 'index.html'));

  // Paths relative to src/ (where the service worker lives); the worker itself is not cached.
  const files = listFiles(SITE)
    .filter((file) => !file.endsWith(`${path.sep}sw.js`) && file !== path.join(SITE, 'index.html'))
    .map((file) => path.relative(path.join(SITE, 'src'), file).split(path.sep).join('/'))
    .sort();
  const hash = crypto.createHash('sha256');
  for (const file of files) hash.update(file).update(fs.readFileSync(path.join(SITE, 'src', file)));
  const version = hash.digest('hex').slice(0, 12);
  fs.writeFileSync(
    path.join(SITE, 'src', 'precache-manifest.js'),
    `// Generated by tools/build-web.js.\nself.PRECACHE = ${JSON.stringify({ version, files: ['precache-manifest.js', ...files] }, null, 2)};\n`,
  );
  process.stdout.write(`_site/ : ${files.length} fichiers, version ${version}\n`);
}

build();
