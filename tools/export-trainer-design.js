// Writes the sprite sources of a portrait design module (tools/trainer-designs/*.js) into
// src/gfx/sources/trainers/<id>.js. Usage: npm run trainer-design -- <design file> [...]
// A design module exports `portraits`: [{ id, portrait }] (48 × 48 battle portrait, atlas frame
// portrait/<id>) and/or `backs`: [{ id, back }] (48 × 48 player seen from behind, frame back/<id>).
// Re-exporting overwrites the sprite file: retouch pixels in the design, not in the export.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { validateSprite } from '../src/gfx/sprite-utils.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = path.join(ROOT, 'src', 'gfx', 'sources', 'trainers');
const RESERVED = ['index', 'portrait-builder'];

const block = (name, rows) => `  ${name}: [\n${rows.map((row) => `    '${row}',`).join('\n')}\n  ],\n`;

/** Source file of one portrait or back view; `view` is 'portrait' or 'back'. */
export function trainerSource(id, view, rows, designFile) {
  if (!/^[a-z0-9_]+$/.test(id) || RESERVED.includes(id)) throw new Error(`Invalid portrait id: ${id}`);
  const errors = validateSprite(rows, { width: 48, height: 48 });
  if (errors.length > 0) throw new Error(`${id}/${view}: ${errors.join('; ')}`);
  return `// ${view}/${id}, generated by npm run trainer-design from ${designFile}.\n`
    + "// 48 × 48: '0'-'3' = palette index, '.' = transparent.\n"
    + 'export default {\n' + block(view, rows) + '};\n';
}

async function main(files) {
  if (files.length === 0) throw new Error('Usage: npm run trainer-design -- <design file> [...]');
  for (const file of files) {
    const designFile = path.relative(ROOT, path.resolve(file)).replace(/\\/g, '/');
    const { portraits = [], backs = [] } = await import(pathToFileURL(path.resolve(file)).href);
    const entries = [...portraits.map((p) => [p.id, 'portrait', p.portrait]), ...backs.map((b) => [b.id, 'back', b.back])];
    for (const [id, view, rows] of entries) {
      fs.writeFileSync(path.join(SOURCES, `${id}.js`), trainerSource(id, view, rows, designFile));
      process.stdout.write(`${view}/${id} ← ${designFile}\n`);
    }
  }
  process.stdout.write('Ajouter les nouveaux portraits à src/gfx/sources/trainers/index.js, puis npm run atlas.\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exit(1);
  });
}
