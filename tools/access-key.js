// npm run key: manages the activation keys of the web version.
//   npm run key -- new "Prénom"     creates a key for someone and prints it (to send them)
//   npm run key -- list             lists the keys created on this computer
//   npm run key -- revoke "Prénom"  revokes a key (by name or id)
// Only the hashes go in src/data/access-keys.js (published). Names and keys stay in
// access-keys.local.json, which is not versioned. Commit and push to apply a change.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hashKey } from '../src/access/access-keys.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_FILE = path.join(ROOT, 'src', 'data', 'access-keys.js');
const LOCAL_FILE = path.join(ROOT, 'access-keys.local.json');
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // no 0/O or 1/I confusion
const GROUPS = 3;
const GROUP_LENGTH = 4;

export function generateKey(randomInt = crypto.randomInt) {
  const groups = Array.from({ length: GROUPS }, () => Array.from({ length: GROUP_LENGTH }, () => ALPHABET[randomInt(ALPHABET.length)]).join(''));
  return groups.join('-');
}

const readLocal = () => (fs.existsSync(LOCAL_FILE) ? JSON.parse(fs.readFileSync(LOCAL_FILE, 'utf8')) : []);

function writeAll(entries) {
  fs.writeFileSync(LOCAL_FILE, `${JSON.stringify(entries, null, 2)}\n`);
  const hashes = entries.map(({ id, hash }) => `  { id: '${id}', hash: '${hash}' },`).join('\n');
  fs.writeFileSync(PUBLIC_FILE, [
    '// Generated by `npm run key` (tools/access-key.js): do not edit by hand.',
    '// Hashes of the activation keys of the web version; `id` is the start of the hash.',
    `export const ACCESS_KEY_HASHES = [${hashes ? `\n${hashes}\n` : ''}];`,
    '',
  ].join('\n'));
}

function main([command, name]) {
  const entries = readLocal();
  if (command === 'new' && name) {
    const key = generateKey();
    const hash = hashKey(key);
    entries.push({ name, key, id: hash.slice(0, 8), hash, created: new Date().toISOString().slice(0, 10) });
    writeAll(entries);
    process.stdout.write(`Clé pour ${name} : ${key}\nCommit et push pour l’activer sur le site.\n`);
  } else if (command === 'list') {
    if (entries.length === 0) process.stdout.write('Aucune clé.\n');
    for (const entry of entries) process.stdout.write(`${entry.id}  ${entry.key}  ${entry.name} (${entry.created})\n`);
  } else if (command === 'revoke' && name) {
    const kept = entries.filter((entry) => entry.name !== name && entry.id !== name);
    if (kept.length === entries.length) {
      process.stderr.write(`Aucune clé pour « ${name} ».\n`);
      process.exitCode = 1;
      return;
    }
    writeAll(kept);
    process.stdout.write(`Clé de ${name} révoquée. Commit et push pour l’appliquer sur le site.\n`);
  } else {
    process.stdout.write('Usage : npm run key -- new "Prénom" | list | revoke "Prénom"\n');
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
